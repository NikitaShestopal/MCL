def clean_text(text):
    """
    Нормалізує та очищує вхідний текст перед шифруванням або криптоаналізом.
    Логіка роботи:
    1. Переводить усі літери у верхній регістр (.upper()).
    2. Ігнорує (видаляє) пробіли, розділові знаки, цифри, дефіси та спецсимволи.
    3. Залишає виключно ті літери, які присутні в константі ALPHABET.
    Це необхідно, оскільки класичний шифр Віженера оперує лише фіксованим алфавітом.
    """
    return ''.join(char for char in text.upper() if char in ALPHABET)