from primes import get_512bit_prime


def egcd(a, b):
    """
    Розширений алгоритм Евкліда (Extended GCD).
    Повертає кошик (НСД, x, y) такий, що: a*x + b*y = gcd(a, b).
    Використовується для знаходження модульного оберненого елемента.
    """
    if a == 0:
        return b, 0, 1
    g, y, x = egcd(b % a, a)
    return g, x - (b // a) * y, y


def mod_inverse(a, m):
    """
    Обчислює модульне обернене значення (a^-1 mod m).
    Якщо НСД чисел не дорівнює 1 — оберненого елемента в кільці не існує.
    """
    g, x, y = egcd(a, m)
    if g != 1:
        raise Exception('Немає оберненого елемента')
    return x % m


def gen_rsa_keys():
    """
    Генерація пари ключів RSA (відкритого та секретного).
    Генерує два 512-бітних простих числа, що дає сумарний модуль n розміром ~1024 біти.
    """
    p = get_512bit_prime()
    q = get_512bit_prime()
    while p == q:
        q = get_512bit_prime()

    n = p * q
    phi = (p - 1) * (q - 1)  # Функція Ейлера від модуля n
    e = 65537  # Стандартна відкрита експонента (F4)
    d = mod_inverse(e, phi)  # Секретна експонента

    # Повертаємо: (відкритий_ключ), (таємний_ключ_з_компонентами_CRT)
    return (e, n), (d, p, q)


def rsa_enc(m, pub):
    """
    Класичне шифрування блоку RSA: c = m^e mod n.
    """
    e, n = pub
    return pow(m, e, n)


def rsa_dec_crt(c, priv):
    """
    Оптимізоване розшифрування RSA за допомогою Китайської теореми про залишки (CRT).
    Замість обчислення m = c^d mod n, операція ділиться на два піднесення до степеня
    за значно меншими модулями 'p' та 'q'. Це дає прискорення роботи приблизно у 3-4 рази.
    """
    d, p, q = priv

    # Зменшуємо секретну експоненту за модулями p-1 та q-1
    dp = d % (p - 1)
    dq = d % (q - 1)
    q_inv = mod_inverse(q, p)  # Попередньо обчислений коефіцієнт відновлення

    # Часткові розшифрування
    m1 = pow(c, dp, p)
    m2 = pow(c, dq, q)

    # Агрегація та відновлення кінцевого результату за схемою Гарнера
    h = (q_inv * (m1 - m2)) % p
    m = m2 + h * q

    return m