from analysis import test_avalanche_effect

def main():
    # Кількість тестів для отримання високої статистичної точності
    TRIALS = 100000

    print("=== Л2.2: Дослідження лавинного ефекту (Стандартні раунди) ===")
    print(f"Кількість випробувань для кожної конфігурації: {TRIALS}\n")

    # Тестування повнорозмірних стандартних криптосистем AES-128, AES-192, AES-256
    for key_len in [16, 24, 32]:
        bits = key_len * 8
        print(f"Тестування AES-{bits}...")
        avg_pt, avg_key = test_avalanche_effect(key_len, trials=TRIALS)
        # Ідеальний показник лавинного ефекту для випадкового шифротексту має становити 64 біти (50% від 128 біт блоку)
        print(f"  Середня кількість змінених бітів при зміні 1 біта відкритого тексту: {avg_pt:.2f} (з 128)")
        print(f"  Середня кількість змінених бітів при зміні 1 біта ключа:             {avg_key:.2f} (з 128)\n")

    print("=== Л2.3: Вплив кількості раундів для AES-128 (Динаміка дифузії) ===")
    # Дослідження покрокового лавиноподібного поширення змін від 1 до 14 раундів
    for r in range(1, 15):
        avg_pt, avg_key = test_avalanche_effect(16, trials=TRIALS, rounds_override=r)
        # Дозволяє наочно побачити, на якому саме раунді алгоритм досягає повної дифузії (~64 біти)
        print(f"Раундів {r:2d}: зміна тексту -> {avg_pt:6.2f} біт | зміна ключа -> {avg_key:6.2f} біт")

if __name__ == "__main__":
    main()